@dataclass
class EventRecord:
    event_type: EventType
    timestamp: int
    details: Dict[str, Any]

class EventLogger:
    def __init__(self):
        self.events: List[EventRecord] = []
    
    def log(self, event_type: EventType, timestamp: int, **details):
        record = EventRecord(event_type=event_type, timestamp=timestamp, details=details)
        self.events.append(record)
    
    def get_events(self) -> List[Dict[str, Any]]:
        return [
            {
                "event_type": e.event_type.value,
                "timestamp": e.timestamp,
                "details": e.details
            }
            for e in self.events
        ]
